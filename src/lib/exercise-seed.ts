import type { Equipment, ExerciseKind, Muscle, StarterExercise } from "./exercises";

type Opts = {
  other?: Muscle[];
  kind?: ExerciseKind;
  perSide?: boolean;
  pr?: boolean;
  rm5?: boolean;
};

function ex(
  key: string,
  nl: [string, string],
  en: [string, string],
  equipment: Equipment,
  primary: Muscle,
  o: Opts = {},
): StarterExercise {
  return {
    key,
    name: { nl: nl[0], en: en[0] },
    instructions: { nl: nl[1], en: en[1] },
    equipment,
    primary_muscle: primary,
    other_muscles: o.other ?? [],
    kind: o.kind ?? "weight_reps",
    per_side: o.perSide ?? false,
    track_pr: o.pr ?? false,
    track_5rm: o.rm5 ?? false,
  };
}

